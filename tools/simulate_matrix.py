def srgb_xyz(rgb):
    return M_srgb @ srgb_encode(np.array(rgb, float) / 255.0)

def lab_to_xyz(Lab):
    L, a, b = Lab
    fy = (L + 16) / 116
    fx = fy + a / 500
    fz = fy - b / 200
    def finv(t):
        d = 6/29
        return t**3 if t > d else 3*d*d*(t - 4/29)
    return np.array([WP_D65[0]*finv(fx), WP_D65[1]*finv(fy), WP_D65[2]*finv(fz)])

