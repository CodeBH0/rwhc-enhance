refs = [lab_to_xyz(np.array(olab)) for _, _, olab, _ in data]

def evaluate(W, name):
    des = []
    for (nm, rgb, olab, mlab), ref in zip(data, refs):
        c = srgb_xyz(rgb)
        r = lab_to_xyz(np.array(mlab)) - c          # v3 显示路径残差
        out = W @ c + r                             # 预测输出
        d = XYZdeltaE2000(out, ref)                 # 对工具的 oLab 参考
        des.append((nm, d))
    avg = sum(d for _, d in des) / len(des)
    mx = max(d for _, d in des)
    print(f"{name:<30} avg={avg:.2f} max={mx:.2f}  worst: " +
          " ".join(f"{n}:{d:.1f}" for n, d in sorted(des, key=lambda x: -x[1])[:5]))
    return avg, des

