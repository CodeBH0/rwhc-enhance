print(f"{'颜色':<6} {'代码':<16} {'R因子':>7} {'G因子':>7} {'B因子':>7}   修正后代码(RGB)")
rows = []
for code, T, O in data:
    T_rgb = M_inv @ np.array(T)
    O_rgb = M_inv @ np.array(O)
    O_rgb = np.maximum(O_rgb, 1e-9)
    f = T_rgb / O_rgb
    f = np.clip(f, 0.5, 2.0)
