def xyY(x, y, Y):
    return np.array([x / y * Y, Y, (1 - x - y) / y * Y])

# 显示器实测原色 (v3, 21:36 测量, nits)
R = xyY(0.675, 0.283, 60.34)
G = xyY(0.213, 0.681, 197.47)
B = xyY(0.152, 0.038, 14.14)
W = xyY(0.299, 0.323, 188.96)
M0 = np.column_stack([R, G, B])
Wn = W / W[1]
s = np.linalg.solve(M0, Wn)
M_display = M0 @ np.diag(s)
M_inv = np.linalg.inv(M_display)

